// 在 viewer-review-server.ts 临时服务上测试真实读写，不接触正式数据。
(async page => {
  const check = (v, m) => { if (!v) throw new Error(m); };
  const errors = []; page.on("pageerror", e => errors.push(e.message));
  await page.goto("http://127.0.0.1:4175/?view=review");
  await page.locator('#nav-review').click();
  await page.locator("#review-form").waitFor();
  await page.locator("#review-reason").fill("未保存的理由");
  await page.evaluate(() => { window.__originalConfirm = window.confirm; window.__reviewWarned = false; window.confirm = () => { window.__reviewWarned = true; return false; }; });
  await page.locator("#nav-review").click();
  check(await page.evaluate(() => window.__reviewWarned) && await page.locator("#review-reason").inputValue() === "未保存的理由", "再次点击当前导航也不能丢弃未保存内容");
  await page.evaluate(() => { window.confirm = window.__originalConfirm; });
  await page.locator("#review-reason").fill("需要历史约定，不在当前项目文件中。");
  await page.locator("#review-query").fill("<img src=x onerror=alert(1)> 查询项目约定");
  const card = page.locator('[data-tool="tdai_memory_search"]');
  await card.hover();
  await card.locator('[role="tooltip"]').waitFor();
  check((await card.locator('[role="tooltip"]').innerText()).includes("L1"), "悬浮展示完整描述");
  await page.locator("#review-save-next").click();
  await page.waitForFunction(() => document.getElementById("review-task-id").textContent === "task_b");
  check(await page.locator("#review-rule-mode").inputValue() === "sequence", "Probe 不能自动转换标签");
  await page.locator("#review-prev").click();
  check((await page.locator("#review-reason").inputValue()).includes("历史约定"), "保存并返回仍保留理由");
  await page.locator('[data-tool="tdai_read_scene"] button').click();
  check(await page.locator("#review-selected-tools button").count() === 2, "点击工具添加允许的首个工具");
  await page.locator("#review-save").click();
  await page.waitForFunction(() => document.getElementById("review-dirty").textContent === "未修改");
  const current = await (await page.request.get("http://127.0.0.1:4175/api/review")).json();
  check(current.items[0].tags[0] === "保留元数据", "保存不得删除其他字段");
  check(current.items[0].query.startsWith("<img"), "HTML 必须按文本保存");
  await page.locator("#review-import-open").click();
  const task = { schema_version: 1, case_id: "task_c", suite: "main", query: "修改变量名", should_call: false, tool_family: "none", reason: "本地信息完整" };
  await page.locator("#review-import-text").fill(JSON.stringify(task));
  await page.locator("#review-import-preview").click();
  await page.locator("#review-import-confirm:not([disabled])").waitFor();
  await page.locator("#review-import-confirm").click();
  await page.waitForFunction(() => !document.getElementById("review-import-dialog").open);
  await page.locator("#review-search").fill("task_c");
  await page.locator("#review-list button").click();
  check(await page.locator("#review-should-call").inputValue() === "false", "新任务保留负例标签");
  check(await page.locator("#review-reason").inputValue() === "本地信息完整", "单条导入保留 reason");
  await page.locator("#review-import-open").click();
  await page.locator("#review-import-file").setInputFiles("/home/liukuan/Tencent-DB-Memory-Project/eval_kit/tests/fixtures/review-import.jsonl");
  await page.waitForFunction(() => document.getElementById("review-import-text").value.includes("task_e"));
  await page.locator("#review-import-preview").click();
  await page.locator("#review-import-confirm:not([disabled])").waitFor();
  check((await page.locator("#review-import-result").innerText()).includes("新增 2 条"), "批量预览统计");
  await page.locator("#review-import-confirm").click();
  await page.waitForFunction(() => !document.getElementById("review-import-dialog").open);
  check((await (await page.request.get("http://127.0.0.1:4175/api/review")).json()).items.length === 5, "批量文件实际写入临时数据集");
  await page.locator("#review-search").fill("");
  await page.locator("#review-reason-filter").selectOption("missing");
  check(await page.locator("#review-list button").count() === 1, "筛选缺少理由的旧任务");
  await page.locator("#review-reason-filter").selectOption("");
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "移动端不能横向溢出");
  check(errors.length === 0, errors.join("\n"));
  return { passed: true, tasks: (await (await page.request.get("http://127.0.0.1:4175/api/review")).json()).items.length };
})
